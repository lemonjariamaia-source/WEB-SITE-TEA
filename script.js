// ---------- Language switch ----------
const english = {};
document.querySelectorAll("[data-i18n]").forEach(el => { english[el.dataset.i18n] = el.innerHTML; });
let lang = "en";
let tlIndex = 0;

function setLanguage(next) {
  lang = next;
  document.documentElement.lang = next;
  document.body.classList.toggle("ka", next === "ka");
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    el.innerHTML = next === "ka" && ka[key] ? ka[key] : english[key];
  });
  document.querySelectorAll("[data-lang]").forEach(b => b.setAttribute("aria-pressed", b.dataset.lang === next));
  document.getElementById("menuToggle").textContent = next === "ka" ? "მენიუ" : "Menu";
  document.getElementById("formStatus").textContent = "";
  renderTimeline();
}
document.querySelectorAll("[data-lang]").forEach(b => b.addEventListener("click", () => setLanguage(b.dataset.lang)));

// ---------- Timeline ----------
function renderTimeline() {
  const years = document.getElementById("years");
  years.innerHTML = "";
  timeline[lang].forEach(([year], i) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.textContent = year;
    btn.setAttribute("aria-pressed", i === tlIndex);
    btn.addEventListener("click", () => { tlIndex = i; renderTimeline(); });
    years.appendChild(btn);
  });
  document.getElementById("tlYear").textContent = timeline[lang][tlIndex][0];
  document.getElementById("tlText").textContent = timeline[lang][tlIndex][1];
}

// ---------- Hero: text changes as you scroll ----------
const track = document.getElementById("home");
const lines = document.querySelectorAll(".story-line");
const hero = document.querySelector(".hero-stage");

function updateHero() {
  const scrollable = track.offsetHeight - window.innerHeight;
  const progress = Math.max(0, Math.min(1, -track.getBoundingClientRect().top / scrollable));
  const active = Math.min(lines.length - 1, Math.floor(progress * lines.length));
  lines.forEach((line, i) => line.classList.toggle("active", i === active));
  hero.style.setProperty("--zoom", 1 + progress * 0.075);
  hero.style.setProperty("--line-opacity", 1 - Math.max(0, Math.min(1, (progress - 0.8) / 0.04)));
  hero.style.setProperty("--end-opacity", Math.max(0, Math.min(1, (progress - 0.84) / 0.16)));
}
window.addEventListener("scroll", updateHero, { passive: true });
window.addEventListener("resize", updateHero);

// ---------- Mobile menu ----------
const nav = document.getElementById("nav");
const toggle = document.getElementById("menuToggle");
toggle.addEventListener("click", () => {
  const open = nav.classList.toggle("open");
  toggle.setAttribute("aria-expanded", open);
});
nav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => nav.classList.remove("open")));

// ---------- Visit form ----------
document.getElementById("visitForm").addEventListener("submit", event => {
  event.preventDefault();
  const email = document.getElementById("email").value.trim();
  const t = visitText[lang];
  window.location.href = "mailto:?subject=" + encodeURIComponent(t.subject) + "&body=" + encodeURIComponent(t.body + " " + email);
  document.getElementById("formStatus").textContent = t.status;
});

